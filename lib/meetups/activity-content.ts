/** Editorial prompts only. Never used to infer attendance, consent or paid state. */
export function getActivityContent(activityKey: string | null, category: string): ActivityContent {
  if (activityKey === 'campus-cafe-chat') return packs.cafe
  if (activityKey === 'campus-small-shop') return packs.shopping
  if (['walking', 'running', 'hiking'].includes(category)) return packs.running
  if (['baseball', 'soccer', 'basketball', 'badminton', 'tennis'].includes(category)) return packs.sport
  return packs[category] ?? packs.other
}
